"""Tools for the lecture deck stored in slides/ (a Claude Slides artifact, one HTML file per slide).

    python tools/deck_tools.py preview   # slides/preview.html: all slides in order, with speaker notes
    python tools/deck_tools.py notes     # notes/speaker-notes.md: titles and speaker notes in order

Only the Python standard library is used.
"""

import html
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SLIDES = ROOT / "slides"


def load():
    deck = json.loads((SLIDES / "project" / "deck.json").read_text())
    out = []
    for sid in deck["order"]:
        src = (SLIDES / "project" / "slides" / f"{sid}.html").read_text()
        m = re.search(r"<aside>(.*?)</aside>", src, re.S)
        note = html.unescape(re.sub(r"<[^>]+>", "", m.group(1))).strip() if m else ""
        body = re.sub(r"<aside>.*?</aside>", "", src, flags=re.S)
        t = re.search(r"<h2[^>]*>(.*?)</h2>", body, re.S)
        title = html.unescape(re.sub(r"<[^>]+>", "", t.group(1))).strip() if t else sid
        out.append(dict(id=sid, title=title, html=body, note=note, hidden=bool(re.search(r"<section[^>]*\shidden", src))))
    return deck, out


def asset_map():
    return {p.stem: p.name for p in (SLIDES / "assets").iterdir()}


def preview():
    deck, slides = load()
    files = asset_map()
    scale = 0.5
    parts = [
        "<!doctype html><meta charset='utf-8'><title>%s</title>" % html.escape(deck["title"]),
        "<style>body{background:#ddd;font-family:Arial,sans-serif;margin:24px}"
        ".wrap{margin:0 auto 8px;width:%dpx}.frame{width:%dpx;height:%dpx;overflow:hidden;background:#fff;box-shadow:0 1px 6px #0004;position:relative}"
        ".frame section{position:absolute;left:0;top:0;width:1920px;height:1080px;box-sizing:border-box;transform:scale(%s);transform-origin:0 0;overflow:hidden}"
        ".frame section *{margin:0;box-sizing:border-box}.frame section ul,.frame section ol{padding-left:1.2em}.frame section img{display:block}"
        ".note{font-size:14px;line-height:1.4;color:#333;margin:6px 0 30px;max-width:%dpx}h4{margin:0 0 4px;color:#00509A}</style>"
        % (int(1920 * scale), int(1920 * scale), int(1080 * scale), scale, int(1920 * scale))
    ]
    for i, s in enumerate(slides, 1):
        body = re.sub(r'/_blob/([0-9a-f]{32})', lambda m: "assets/" + files.get(m.group(1), m.group(1)), s["html"])
        body = re.sub(r"\shidden", "", body, count=1)
        tag = " (hidden in the deck)" if s["hidden"] else ""
        parts.append(
            f"<div class='wrap'><h4>{i}. {html.escape(s['title'])}{tag}</h4><div class='frame'>{body}</div>"
            f"<div class='note'>{html.escape(s['note'])}</div></div>"
        )
    (SLIDES / "preview.html").write_text("\n".join(parts))
    print("wrote", SLIDES / "preview.html", f"({len(slides)} slides)")


def notes():
    deck, slides = load()
    sections = {v["start"]: k for k, v in deck.get("sections", {}).items()}
    lines = [f"# {deck['title']}: speaker notes\n",
             "Generated by `tools/deck_tools.py notes` from the speaker notes of the slides. "
             "Edit the slides, not this file.\n"]
    for i, s in enumerate(slides, 1):
        if s["id"] in sections:
            lines.append(f"\n## Section: {sections[s['id']]}\n")
        hid = " (hidden)" if s["hidden"] else ""
        lines.append(f"\n### {i}. {s['title']}{hid}\n\n{s['note'] or '(no notes)'}\n")
    out = ROOT / "notes"
    out.mkdir(exist_ok=True)
    (out / "speaker-notes.md").write_text("\n".join(lines))
    print("wrote", out / "speaker-notes.md")


if __name__ == "__main__":
    {"preview": preview, "notes": notes}[sys.argv[1] if len(sys.argv) > 1 else "preview"]()
